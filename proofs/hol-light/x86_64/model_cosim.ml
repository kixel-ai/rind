(* pushq X(%rsp) between leaq 16(%rsp),%rsp and leaq -8(%rsp),%rsp, so it
   reads and writes within the harness's 256-byte buffer and leaves RSP as
   it was. *)
let rind_push_cases = map (fun x ->
  [[0x48; 0x8d; 0x64; 0x24; 0x10]; [0xff; 0x74; 0x24; x];
   [0x48; 0x8d; 0x64; 0x24; 0xf8]]) [0x00; 0x08; 0x60; 0x78];;

let rind_cosim name runs f =
  for i = 1 to runs do
    let decoded, ok = f () in
    if not ok then
     (Printf.printf "Error: the model disagrees with the CPU on %s\n%!"
        (string_of_term decoded);
      failwith "cosim")
  done;
  Printf.printf "agrees: %s\n%!" name;;

sematest_random_init ();;
List.iter (fun b -> rind_cosim (String.concat " " (map string_of_int b)) 20
  (fun () -> cosimulate_instructions None 0 [b])) rind_reg_cases;;
List.iter (fun b -> rind_cosim (String.concat " " (map string_of_int b)) 20
  (fun () -> cosimulate_instructions (Some 0) 32 [b])) rind_mem_cases;;
List.iter (fun bs -> rind_cosim "pushq m64" 20
  (fun () -> cosimulate_instructions (Some 1) 0 bs)) rind_push_cases;;
